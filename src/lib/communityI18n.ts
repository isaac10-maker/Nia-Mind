const ERROR_CODES = [
  'COMMUNITY_NOT_AUTHENTICATED',
  'COMMUNITY_FORBIDDEN',
  'COMMUNITY_INVALID_URL',
  'COMMUNITY_INVALID_COVER',
  'COMMUNITY_USER_NOT_FOUND',
  'COMMUNITY_REASON_REQUIRED',
  'COMMUNITY_SENSITIVE_ACK_REQUIRED',
  'COMMUNITY_UNSAFE_TEXT',
  'COMMUNITY_INVALID_STATUS',
  'COMMUNITY_NOT_OWNER',
  'COMMUNITY_NOT_FOUND',
  'COMMUNITY_CATEGORY_INACTIVE',
] as const;

export function communityErrorMessage(lang: LanguageCodeInput, raw: string): string {
  const text = raw || '';
  if (text.includes('COMMUNITY_USER_NOT_FOUND')) return tCommunityExtra(lang, 'userMissing');
  if (text.includes('COMMUNITY_INVALID_URL') || text.includes('COMMUNITY_INVALID_COVER')) {
    return tCommunityExtra(lang, 'invalidUrl');
  }
  if (text.includes('COMMUNITY_REASON_REQUIRED')) return tCommunityExtra(lang, 'reasonRequired');
  if (text.includes('COMMUNITY_SENSITIVE_ACK_REQUIRED')) return tCommunityExtra(lang, 'sensitiveRequired');
  if (text.includes('COMMUNITY_UNSAFE_TEXT')) return tCommunityExtra(lang, 'unsafeText');
  if (text.includes('COMMUNITY_FORBIDDEN') || text.includes('COMMUNITY_NOT_OWNER') || text.includes('COMMUNITY_NOT_AUTHENTICATED')) {
    return tCommunityExtra(lang, 'forbidden');
  }
  if (ERROR_CODES.some((code) => text.includes(code))) return tCommunityExtra(lang, 'unknownError');
  return tCommunityExtra(lang, 'unknownError');
}
